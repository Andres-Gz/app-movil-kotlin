-- Configuración de las cuentas de Finanzia en Supabase.
--
-- Se corre una vez en el SQL Editor del proyecto (Supabase → SQL Editor → New query → Run).
-- Se puede volver a correr sin problema: no borra datos ni duplica nada.
--
-- Hace tres cosas:
--   1. Crea la fila de `usuarios` sola cuando alguien se registra (la app no escribe en esa tabla).
--   2. Deja que cada usuario con sesión lea solo su propia fila (lo usa el inicio de sesión).
--   3. Protege el resto de tablas: nadie las lee ni las escribe por la API hasta que tengan sus reglas.


-- 1. Perfil automático al registrarse ----------------------------------------------------------

-- La contraseña la guarda Supabase Auth, así que en las cuentas nuevas esta columna queda vacía.
alter table public.usuarios alter column contrasena drop not null;

-- El id se numera solo (si todavía no lo hacía), siguiendo después del último que ya exista.
do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'usuarios'
      and column_name = 'id_usuario'
      and column_default is null
      and is_identity = 'NO'
  ) then
    alter table public.usuarios alter column id_usuario set not null;
    alter table public.usuarios alter column id_usuario add generated by default as identity;
    perform setval(
      pg_get_serial_sequence('public.usuarios', 'id_usuario'),
      coalesce((select max(id_usuario) from public.usuarios), 0) + 1,
      false
    );
  end if;
end $$;

-- Copia el nombre (que la app manda al registrarse) y el correo de la cuenta nueva.
create or replace function public.crear_perfil_usuario()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from public.usuarios where lower(correo) = lower(new.email)) then
    insert into public.usuarios (nombre, correo)
    values (
      coalesce(nullif(trim(new.raw_user_meta_data ->> 'nombre'), ''), split_part(new.email, '@', 1)),
      new.email
    );
  end if;
  return new;
end;
$$;

drop trigger if exists al_crear_cuenta on auth.users;
create trigger al_crear_cuenta
  after insert on auth.users
  for each row execute function public.crear_perfil_usuario();

-- Cuentas que ya existían en Auth y no tenían su fila en `usuarios`.
insert into public.usuarios (nombre, correo)
select
  coalesce(nullif(trim(cuenta.raw_user_meta_data ->> 'nombre'), ''), split_part(cuenta.email, '@', 1)),
  cuenta.email
from auth.users as cuenta
where cuenta.email is not null
  and not exists (select 1 from public.usuarios as perfil where lower(perfil.correo) = lower(cuenta.email));


-- 2. Cada usuario lee solo su perfil -----------------------------------------------------------

alter table public.usuarios enable row level security;

drop policy if exists "Cada usuario lee su perfil" on public.usuarios;
create policy "Cada usuario lee su perfil"
  on public.usuarios
  for select
  to authenticated
  using (lower(correo) = lower(auth.jwt() ->> 'email'));

-- Solo las columnas que usa la app: la contraseña nunca se puede leer. Primero se quitan los permisos
-- que algunos proyectos nuevos dan solos a todas las tablas.
revoke all on public.usuarios from anon, authenticated;
grant select (id_usuario, nombre, correo) on public.usuarios to authenticated;


-- 3. Proteger el resto de tablas ---------------------------------------------------------------

-- Con la clave publicable cualquiera puede llamar a la API. Con RLS activado y sin reglas,
-- nadie lee ni escribe esas tablas hasta que cada pantalla agregue las suyas.
do $$
declare
  tabla record;
begin
  for tabla in select tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table public.%I enable row level security', tabla.tablename);
  end loop;
end $$;
